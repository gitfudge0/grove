use super::{
    contract::{hash, Snapshot},
    document::{Document, Kind, Node, State, Width},
};
use std::fmt::Write as _;

pub fn generate(doc: &Document, s: &Snapshot) -> Result<String, String> {
    super::document::validate(doc, s)?;
    let mut out=format!("// @generated by {}; DO NOT EDIT.\n// layout: {}\n// native contract: {}\nuse gpui::{{prelude::*, div, AnyElement}};\nuse crate::ui_reference::compose as native;\nuse crate::views::{{rpx, tokens::*}};\npub fn render(bindings: &native::Bindings, window: &mut gpui::Window, cx: &mut gpui::App) -> AnyElement {{\n",s.generator_version,layout_hash(doc),hash(serde_json::to_vec(&(&s.owners,&s.tokens,&s.font_hashes,&s.dense_action)).unwrap()));
    let mut fields = String::new();
    for action in &doc.actions {
        write!(fields, "pub {action}: native::Action,").unwrap();
    }
    for name in doc.values.keys() {
        write!(fields, "pub {name}: gpui::SharedString,").unwrap();
    }
    out = out.replace(
        "pub fn render(bindings: &native::Bindings",
        &format!("pub const LAYOUT_HASH: &str = {:?};\npub struct Bindings {{{fields}}}\npub fn render(bindings: &Bindings", layout_hash(doc)),
    );
    let mut fixture_fields = String::new();
    for action in &doc.actions {
        write!(fixture_fields,"{action}: {{let callback=on_action.clone();std::rc::Rc::new(move|_,window,cx|callback({action:?},window,cx))}},").unwrap();
    }
    for (name, value) in &doc.values {
        write!(fixture_fields, "{name}: {}.into(),", q(value)).unwrap();
    }
    let constructor=format!("#[cfg(test)] impl Bindings {{pub fn fixture(on_action:native::FixtureAction)->Self {{Self{{{fixture_fields}}}}}}}\n");
    out = out.replace("pub fn render(", &format!("{constructor}pub fn render("));
    out.push_str(&node(&doc.root));
    out.push_str("\n}\n");
    format_rust(&out)
}

/// One rule used by measured composition and the production owning view.
pub fn generate_dense_action() -> Result<String, String> {
    format_rust(
        r"// @generated by grove-reference-1; DO NOT EDIT. Recipe: dense_action/1.
use gpui::{prelude::*, App, Window};
use gpui_component::{button::Button, Disableable};
use super::DenseActionBindings;

pub(crate) fn dense_action(bindings: DenseActionBindings, window: &Window, cx: &App) -> Button {
    crate::views::components::dense_action_with_colors(
        bindings.id, bindings.label, crate::theme::BG_RAIL(),
        crate::theme::FG_DIM(), crate::theme::BG_HOVER(), window, cx,
    )
    .when_some(bindings.icon, Button::icon)
    .disabled(bindings.disabled)
    .loading(bindings.loading)
    .on_click(move |event, window, cx| (bindings.on_activate)(event, window, cx))
}
",
    )
}
fn format_rust(out: &str) -> Result<String, String> {
    use std::io::Write as _;
    let mut formatter = std::process::Command::new("rustfmt")
        .args(["--edition", "2021"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .map_err(|e| format!("reference generation requires pinned rustfmt: {e}"))?;
    formatter
        .stdin
        .take()
        .ok_or("rustfmt stdin missing")?
        .write_all(out.as_bytes())
        .map_err(|e| e.to_string())?;
    let result = formatter.wait_with_output().map_err(|e| e.to_string())?;
    if !result.status.success() {
        return Err(format!(
            "generated Rust failed formatting: {}",
            String::from_utf8_lossy(&result.stderr)
        ));
    }
    String::from_utf8(result.stdout).map_err(|e| e.to_string())
}
fn q(v: &str) -> String {
    format!("{v:?}")
}
fn text_value(n: &Node) -> String {
    n.text_binding.as_ref().map_or_else(
        || q(n.text.as_ref().unwrap()),
        |key| format!("bindings.{key}.as_ref()"),
    )
}
fn token(v: &str) -> String {
    v.to_ascii_uppercase()
}
fn node(n: &Node) -> String {
    let id = q(&n.id);
    let fill = n.layout.width == Width::Fill;
    let kind = serde_json::to_value(n.kind)
        .unwrap()
        .as_str()
        .unwrap()
        .to_owned();
    let body = match n.kind {
        Kind::Row | Kind::Column | Kind::Surface => {
            let mut b = String::from("div().flex()");
            if n.kind != Kind::Row {
                b.push_str(".flex_col()");
            }
            write!(
                b,
                ".w_full().gap(rpx({})).p(rpx({}))",
                token(&n.layout.gap),
                token(&n.layout.padding)
            )
            .unwrap();
            for child in &n.children {
                write!(b, ".child({})", node(child)).unwrap();
            }
            if n.kind == Kind::Surface {
                format!("native::surface({id}, {b})")
            } else {
                b
            }
        }
        Kind::Text => format!(
            "native::text({id}, {}, {}, {}, window, cx)",
            text_value(n),
            token(n.text_role.as_ref().unwrap()),
            q(n.color.as_ref().unwrap())
        ),
        Kind::Icon => format!(
            "native::catalog_icon({id}, {}, crate::theme::FG())",
            q(n.icon.as_ref().unwrap())
        ),
        Kind::DenseAction => format!(
            "native::action({id}, {}, {}, {}, bindings.{}.clone(), window, cx)",
            text_value(n),
            n.icon
                .as_ref()
                .map_or("None".into(), |s| format!("Some({})", q(s))),
            q(match n.state {
                State::Rest => "rest",
                State::Hover => "hover",
                State::Focus => "focus",
                State::Disabled => "disabled",
                State::Loading => "loading",
            }),
            n.action.as_ref().unwrap()
        ),
        Kind::CheckoutRow => format!(
            "native::checkout({id}, {}, {}, {}, window, cx)",
            text_value(n),
            q(n.icon.as_ref().unwrap()),
            node(&n.children[0])
        ),
    };
    format!(
        "native::measure({id}, {}, {fill}, {body}.into_any_element())",
        q(&kind)
    )
}

pub fn layout_hash(doc: &Document) -> String {
    hash(serde_json::to_vec(&(&doc.root, &doc.actions, &doc.values)).unwrap())
}

/// Stable owner selectors distinguish the container from observed inner slots.
pub fn selector_map(doc: &Document) -> std::collections::BTreeMap<String, serde_json::Value> {
    let mut result = std::collections::BTreeMap::new();
    doc.root.walk(&mut|node|{
        let owner=format!("ui-reference-{}",node.id);
        result.insert(node.id.clone(),serde_json::json!({"owner_selector":owner,"measurement":"first-child-bounds"}));
        if matches!(node.kind,Kind::DenseAction|Kind::CheckoutRow){
            let label=format!("{}-label",node.id);
            result.insert(label.clone(),if node.kind==Kind::DenseAction{serde_json::json!({"owner_selector":owner,"measurement":"vendor-label-text-layout","native_slot":"label"})}else{serde_json::json!({"owner_selector":format!("ui-reference-{label}"),"measurement":"allocated-label-container-and-shaped-inner-text"})});
            if node.icon.is_some(){let icon=format!("{}-icon",node.id);result.insert(icon.clone(),if node.kind==Kind::DenseAction{serde_json::json!({"owner_selector":owner,"measurement":"vendor-content-child-bounds","native_slot":"leading-icon"})}else{serde_json::json!({"owner_selector":format!("ui-reference-{icon}"),"measurement":"first-child-bounds"})});}
        }
    });
    result
}
