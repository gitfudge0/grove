//
// gpui-component binds `up`/`down`/`left`/`right`/`tab`/`shift-tab`/`enter`
// in the plain `"Input"` context, and a matched binding stops dispatch before
// the modal layer's bubble-phase `on_key_down` ever runs. These actions are
