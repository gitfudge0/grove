        let per_dir = 1 + grid_swap_prefixes().len();
        assert_eq!(grid_bindings().len(), GRID_DIRECTIONS.len() * per_dir);
        assert_eq!(term_panel_bindings().len(), 2);
        assert_eq!(zen_focus_bindings().len(), 2);
