use std::sync::RwLock;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum ThemeKind {
    Dark,
    Light,
}

#[derive(Clone, Copy)]
pub enum Color {
    Rgb(u8, u8, u8),
}

#[derive(Clone, Copy)]
pub struct Theme {
    pub name: &'static str,
    pub kind: ThemeKind,
    pub bg: Color,
    pub bg_highlight: Color,
    pub fg: Color,
    pub fg_dark: Color,
    pub comment: Color,
    pub blue: Color,
    pub cyan: Color,
    pub magenta: Color,
    pub green: Color,
    pub yellow: Color,
    pub red: Color,
}

const fn rgb(r: u8, g: u8, b: u8) -> Color {
    Color::Rgb(r, g, b)
}

